export const isCollidable = (col: number, row: number): boolean => {
    if (col < 0 || col >= COLS || row < 0 || row >= ROWS) {
        return true;
    }
    return COLLISION_MAP[row][col] === 1;
};

export const isPositionCollidable = (px: number, py: number, tileSize: number): boolean => {
    const col = Math.floor(px / tileSize);
    const row = Math.floor(py / tileSize);
    return isCollidable(col, row);
};
